#include "oled.h"

/*========软件I2C========*/
#define SCL_H  HAL_GPIO_WritePin(OLED_SCL_PORT,OLED_SCL_PIN,GPIO_PIN_SET)
#define SCL_L  HAL_GPIO_WritePin( OLED_SCL_PORT,OLED_SCL_PIN,GPIO_PIN_RESET)
#define SDA_H  HAL_GPIO_WritePin(OLED_SDA_PORT,OLED_SDA_PIN,GPIO_PIN_SET)
#define SDA_L  HAL_GPIO_WritePin(OLED_SDA_PORT,OLED_SDA_PIN, GPIO_PIN_RESET)

//延时（72MHz）
static void Delay_us(uint32_t us) {
    while(us--) { for(volatile int i=0; i<16; i++); }
}

static void I2C_Start(void) {
    SDA_H; SCL_H; Delay_us(5);
    SDA_L; Delay_us(5);
    SCL_L;
}

static void I2C_Stop(void) {
    SDA_L; SCL_H; Delay_us(5);
    SDA_H; Delay_us(5);
}

static void I2C_SendByte(uint8_t dat) {
    for(uint8_t i=0; i<8; i++) {
        if(dat & 0x80) SDA_H; else SDA_L;
        dat <<= 1;
        SCL_H; Delay_us(5);
        SCL_L; Delay_us(5);
    }
    SDA_H; // 释放 SDA
    SCL_H; Delay_us(5); //无视 ACK
    SCL_L;
}

static void OLED_WriteCmd(uint8_t cmd) {
    I2C_Start(); 
    I2C_SendByte(0x78); // 地址 0x78 (如果不行改成 0x7A)
    I2C_SendByte(0x00); 
    I2C_SendByte(cmd); 
    I2C_Stop();
}

static void OLED_WriteData(uint8_t dat) {
    I2C_Start(); 
    I2C_SendByte(0x78); // 地址 0x78 (如果不行改成 0x7A)
    I2C_SendByte(0x40); 
    I2C_SendByte(dat); 
    I2C_Stop();
}
// 设置显示位置 (x: 0-127, page: 0-7)
static void OLED_SetPos(uint8_t x, uint8_t page) {
    OLED_WriteCmd(0xB0 + page);
    OLED_WriteCmd(((x & 0xF0) >> 4) | 0x10);
    OLED_WriteCmd((x & 0x0F) | 0x00);
}



