/*========等待上电稳定========*/
void OLED_Init(void)
{
	HAL_Delay(500);


 // === 1. 发送开机指令序列 ===
  OLED_WriteCmd(0xAE); 
  OLED_WriteCmd(0x20); 
  OLED_WriteCmd(0x00);
  OLED_WriteCmd(0xB0); 
  OLED_WriteCmd(0xC8); //上下方向
  OLED_WriteCmd(0x00);
  OLED_WriteCmd(0x10); 
  OLED_WriteCmd(0x40); 
  OLED_WriteCmd(0x81); 
  OLED_WriteCmd(0xCF); 
  OLED_WriteCmd(0xA1); //左右方向
  OLED_WriteCmd(0xA7); //若反色则改成A6
  OLED_WriteCmd(0xA8); 
  OLED_WriteCmd(0x3F); 
  OLED_WriteCmd(0xA4); 
  OLED_WriteCmd(0xD3); 
  OLED_WriteCmd(0x00); 
  OLED_WriteCmd(0xD5); 
  OLED_WriteCmd(0x80); 
  OLED_WriteCmd(0xD9); 
  OLED_WriteCmd(0xF1); 
  OLED_WriteCmd(0xDA); 
  OLED_WriteCmd(0x12); 
  OLED_WriteCmd(0xDB); 
  OLED_WriteCmd(0x40); 
  OLED_WriteCmd(0x8D); 
  OLED_WriteCmd(0x14); //升压开启，若黑屏改成0x10
  OLED_WriteCmd(0xAF); //开启显示
}
  
//清屏函数
void OLED_Clear(void) 
{
       for(uint8_t page=0; page<8; page++) 
    {
        OLED_WriteCmd(0xB0 + page);         
        OLED_WriteCmd(0x00);        
        OLED_WriteCmd(0x10);                
        for(uint8_t col=0; col<128; col++) 
        {
            OLED_WriteData(0x00);   
        }
    }
}


void OLED_ShowChar(uint8_t x, uint8_t page, char ch) {
    OLED_SetPos(x, page);
    uint8_t c = ch - ' '; // 计算在字库中的偏移量
    if (c > 90) c = 0;    // 防止越界
    
    for(uint8_t i=0; i<6; i++) {
        OLED_WriteData(F6x8[c][i]); 
    }
}

// 字符串显示函数
void OLED_ShowString(uint8_t x, uint8_t page, char *str) {
    while(*str != '\0') {
        OLED_ShowChar(x, page, *str);
        x += 6; // 每个字符宽 6 个像素
        str++;
	if (x > 122) break;
    }
}

